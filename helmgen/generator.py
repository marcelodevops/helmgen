def image_repo(image):
    """Extract the repository from a docker image reference.

    'registry.example.com/library/postgres:14@sha256:abc...' -> 'postgres'
    """
    s = str(image or "").split("@", 1)[0]
    s = s.rsplit("/", 1)[-1]
    if ":" in s:
        s = s.split(":", 1)[0]
    return s

def is_database(image):
    """True only when the image repository itself is a known database.

    Matches on the repo name (bitnami/postgresql, mongo, redis:7-alpine) so
    sidecars like prometheus/postgres-exporter are not misdetected.
    """
    return image_repo(image) in DATABASE_REPOS

def _tokens(key):
    return [t for t in re.split(r"[^A-Z0-9]+", key) if t]

def _remove_seq(tokens, seq):
    n, out = len(seq), []
    i = 0
    while i < len(tokens):
        if tokens[i:i + n] == seq:
            i += n
            continue
        out.append(tokens[i])
        i += 1
    return out

def is_sensitive_key(name, extra=()):
    """Heuristic secret detection on an env var name.

    Matches per token, exactly or as a suffix (so PGPASSWORD and DB_PASS are
    caught, but KEY inside KEYCLOAK is not), and drops known non-secret
    phrases such as PUBLIC_KEY or KEYSTORE before deciding.
    """
    key = str(name).upper()
    if extra and key in {str(e).strip().upper() for e in extra if str(e).strip()}:
        return True

    tokens = _tokens(key)
    for exclusion in SENSITIVE_EXCLUSIONS:
        tokens = _remove_seq(tokens, _tokens(exclusion))
    return any(tok == s or tok.endswith(s) for tok in tokens for s in SENSITIVE_KEYS)

def detect_sensitive_env(env_dict, extra_sensitive=()):
    sensitive = {}
    normal = {}
    for k, v in env_dict.items():
        if is_sensitive_key(k, extra_sensitive):
            sensitive[k] = "<secret-from-values>"
        else:
            normal[k] = v
    return normal, sensitive

def normalize_labels(labels):
    """Compose labels may be a map or a KEY=VAL list; return a flat dict."""
    if isinstance(labels, dict):
        return {str(k): str(v) for k, v in labels.items()}
    out = {}
    for item in labels or []:
        if isinstance(item, str) and "=" in item:
            k, v = item.split("=", 1)
            out[k.strip()] = v.strip()
        elif isinstance(item, dict):
            out.update(normalize_labels(item))
    return out

_TRAEFIK_ROUTER_KEY_RE = re.compile(r"^traefik\.(?:https?)\.routers\.[^.]+\.(.+)$", re.I)

def _traefik_field(key):
    """Traefik rule field (after the router name) from a router label key."""
    m = _TRAEFIK_ROUTER_KEY_RE.match(str(key).strip())
    return m.group(1).lower() if m else None

def _rule_hostsets(value):
    """Host sets from a Traefik rule: Host(`a`,`b`) (v3) or Host:a,b (v1/v2)."""
    sets = [
        [h.strip("`\"'") for h in re.split(r"[,;\s]+", part) if h.strip("`\"'")]
        for part in re.findall(r"Host\(([^)]*)\)", value, re.I)
    ]
    for part in re.findall(r"Host:([A-Za-z0-9.,_.*-]+)", value, re.I):
        hosts = [h.strip("`\"'") for h in part.split(",")]
        sets.append([h for h in hosts if h])
    return sets

def _rule_paths(value):
    """Paths from Path(/a) / PathPrefix(/b) (v3) or Path:/a (v1/v2) rules."""
    paths = re.findall(r"(?:PathPrefix|Path)\(([^)]*)\)", value, re.I)
    paths += re.findall(r"Path(?:Prefix)?:([^\s,;]+)", value, re.I)
    out = []
    for p in paths:
        p = p.strip().strip("`\"'")
        if p.startswith("/"):
            out.append(p)
    return out

def parse_port_string(p):
    """Parse a compose port string like '8080:80/tcp' into (published, container) ints."""
    parts = str(p).split(":")
    try:
        container = int(parts[-1].split("/")[0])
    except ValueError:
        return None, None
    published = None
    if len(parts) > 1 and parts[-2].isdigit():
        published = int(parts[-2])
    return published, container

def normalize_port_entry(p):
    """Normalize a compose port (short string or long-syntax map) to
    {containerPort, published?, protocol?, mode?}. Host-only mappings without
    a container target (e.g. "127.0.0.1:8080:8080" style host_ip+published with
    no target, or long syntax with only published) return None."""
    if isinstance(p, str):
        published, container = parse_port_string(p)
        if container is None:
            return None
        entry = {"containerPort": container}
        if published is not None:
            entry["published"] = published
        if "/udp" in p.lower():
            entry["protocol"] = "UDP"
        return entry
    if isinstance(p, dict):
        target = p.get("target") or p.get("containerPort")
        if target is None:
            return None
        entry = {"containerPort": int(target)}
        if p.get("published") is not None:
            entry["published"] = int(p["published"])
        if p.get("protocol"):
            entry["protocol"] = str(p["protocol"]).upper()
        if p.get("mode"):
            entry["mode"] = str(p["mode"])
        return entry
    return None

def normalize_ports(ports):
    """Normalize compose ports, skipping host-only entries with a warning."""
    out = []
    for p in ports or []:
        entry = normalize_port_entry(p)
        if entry is None:
            warn(f"ignoring port mapping {p!r}: no container target port")
            continue
        out.append(entry)
    return out

def compose_resources_to_k8s(resources):
    """Convert compose deploy.resources.{limits,requests} to K8s quantities."""
    out = {}
    for role in ("requests", "limits"):
        vals = resources.get(role) or {}
        mapped = {}
        if "cpus" in vals:
            mapped["cpu"] = f"{int(float(vals['cpus']) * 1000)}m"
        elif "cpu" in vals:
            mapped["cpu"] = str(vals["cpu"])
        if "memory" in vals:
            mapped["memory"] = str(vals["memory"])
        if mapped:
            out[role] = mapped
    return out

def parse_compose_duration(value):
    """Convert a compose duration like '30s', '500ms' or '1m' to whole seconds."""
    m = re.match(r"^(\d+(?:\.\d+)?)(ms|s|m|h)?$", str(value).strip())
    if not m:
        return None
    num, unit = float(m.group(1)), m.group(2) or "s"
    seconds = num * {"ms": 0.001, "s": 1, "m": 60, "h": 3600}[unit]
    return max(int(seconds), 1)

def parse_healthcheck_probe(hc):
    """Build a base Kubernetes probe from a compose healthcheck mapping, or None."""
    test = hc.get("test")
    if not test:
        return None

    if isinstance(test, list):
        cmd = [str(x) for x in test]
        if cmd and cmd[0].upper() in ("CMD", "CMD-SHELL", "NONE"):
            cmd = cmd[1:]
        if len(cmd) == 1:
            cmd = shlex.split(cmd[0])
    else:
        cmd = shlex.split(str(test))
    if not cmd:
        return None

    url = next((a for a in cmd if a.lower().startswith(("http://", "https://"))), None)
    if url:
        m = re.match(r"https?://[^/:]+(?::(\d+))?(/[^?#]*)?", url, re.I)
        if m:
            default_port = 443 if url.lower().startswith("https") else 80
            probe = {"httpGet": {
                "path": m.group(2) or "/",
                "port": int(m.group(1)) if m.group(1) else default_port,
            }}
        else:
            probe = {"exec": {"command": cmd}}
    else:
        probe = {"exec": {"command": cmd}}

    def duration(field):
        value = hc.get(field)
        return parse_compose_duration(value) if value is not None else None

    timeout = duration("timeout")
    interval = duration("interval")
    if timeout:
        probe["timeoutSeconds"] = timeout
    if interval:
        probe["periodSeconds"] = interval
    if hc.get("retries") is not None:
        probe["failureThreshold"] = int(hc["retries"])
    return probe

def detect_probes(service):
    """Build a Kubernetes probe from a compose healthcheck, or None."""
    hc = service.get("healthcheck") or {}
    if hc.get("disable"):
        return None
    return parse_healthcheck_probe(hc)

def map_healthcheck(service):
    """Map a compose healthcheck to liveness/readiness/startup probe dicts.

    HTTP healthchecks are suitable for both liveness and readiness. Exec
    checks (pg_isready, curl-to-a-dependency) usually test reachability of
    something external, so they only become a readinessProbe — as a liveness
    probe they would restart containers whenever a dependency is down.
    compose start_period becomes a startupProbe rather than delaying liveness.
    """
    hc = service.get("healthcheck") or {}
    if hc.get("disable"):
        return {}
    probe = parse_healthcheck_probe(hc)
    if not probe:
        return {}

    probes = {}
    if "exec" in probe:
        probes["readinessProbe"] = copy.deepcopy(probe)
    else:
        probes["livenessProbe"] = copy.deepcopy(probe)
        probes["readinessProbe"] = copy.deepcopy(probe)

    start_period = parse_compose_duration(hc.get("start_period")) if hc.get("start_period") else None
    if start_period and start_period > 1:
        startup = copy.deepcopy(probe)
        startup.pop("periodSeconds", None)
        startup.pop("failureThreshold", None)
        startup["initialDelaySeconds"] = start_period
        startup.setdefault("timeoutSeconds", 3)
        startup["periodSeconds"] = 5
        startup["failureThreshold"] = 120
        probes["startupProbe"] = startup
    return probes

def normalize_depends_on(depends_on):
    """Compose depends_on accepts a string, list, or long-syntax map; return a list of names."""
    if not depends_on:
        return []
    if isinstance(depends_on, str):
        return [depends_on]
    if isinstance(depends_on, dict):
        return list(depends_on.keys())
    return [str(d) for d in depends_on]

def normalize_networks(networks):
    """Compose networks may be a list of names or a map; return a list of names."""
    if not networks:
        return []
    if isinstance(networks, dict):
        return list(networks.keys())
    return [str(n) for n in networks]


def normalize_volume_mounts(volumes, storage_size="1Gi"):
    """Convert named Compose volumes to per-pod PVC-backed mounts."""
    mounts = []
    source_names = {}
    used_names = set()
    for index, volume in enumerate(volumes or []):
        source = ""
        read_only = False
        if isinstance(volume, str):
            parts = volume.split(":")
            if len(parts) == 1:
                target = parts[0]
            else:
                source, target = parts[0], parts[1]
                read_only = len(parts) > 2 and "ro" in parts[2].split(",")
            mount_type = (
                "bind"
                if source.startswith(("/", "./", "../", "~/", ".\\", "..\\"))
                or "/" in source
                or re.match(r"^[A-Za-z]:[\\/]", source)
                else "volume"
            )
        elif isinstance(volume, dict):
            source = str(volume.get("source") or "")
            target = volume.get("target")
            read_only = bool(volume.get("read_only", False))
            mount_type = volume.get("type") or (
                "bind" if source.startswith(("/", "./", "../", "~/")) else "volume"
            )
        else:
            warn(f"ignoring unsupported volume entry {volume!r}")
            continue

        if not target:
            warn(f"ignoring volume entry {volume!r}: no container target")
            continue
        if mount_type != "volume":
            warn(
                f"service volume {volume!r} is a {mount_type} mount and cannot be "
                "represented portably in a Helm chart; configure it manually"
            )
            continue

        identity = source or f"anonymous-{index + 1}"
        if identity not in source_names:
            slug = re.sub(r"[^a-z0-9-]+", "-", identity.lower()).strip("-") or "data"
            base = f"volume-{slug[:55]}".rstrip("-")
            name = base
            suffix = 2
            while name in used_names:
                ending = f"-{suffix}"
                name = f"{base[:63 - len(ending)]}{ending}"
                suffix += 1
            source_names[identity] = name
            used_names.add(name)

        mounts.append({
            "name": source_names[identity],
            "mountPath": str(target),
            "size": storage_size,
            "readOnly": read_only,
        })
    return mounts


def detect_ingress(service, ingress_class="nginx", base_domain=None):
    labels = normalize_labels(service.get("labels"))
    ports = service.get("ports", [])
    tls = False

    host_sets = []
    paths = []
    for key, val in labels.items():
        val = str(val)
        if re.search(r"Host\s*[(:]", val, re.I):
            host_sets.extend(_rule_hostsets(val))
            if re.search(r"(?:^|[\s(&|])tls(?=$|[\s)&|])", val.lower()):
                tls = True
        if str(key).lower().startswith("traefik.https.routers."):
            tls = True  # router attached to the secure entrypoint
        field = _traefik_field(key)
        if field and field.split(".")[0] == "tls" and val.strip().lower() != "false":
            tls = True
        paths.extend(_rule_paths(val))
    paths = list(dict.fromkeys(paths)) or ["/"]
    if base_domain:
        tls = True

    container_ports = []
    for p in ports:
        if isinstance(p, str):
            _, port_num = parse_port_string(p)
        elif isinstance(p, dict):
            port_num = p.get("target") or p.get("containerPort") or p.get("published")
        else:
            port_num = None
        if port_num:
            port_num = int(port_num)
            if port_num not in container_ports:
                container_ports.append(port_num)
    if 443 in container_ports:
        tls = True

    first_port = container_ports[0] if container_ports else 80
    rules = []

    configured_host = next(
        (labels[k] for k in ("ingress.host", "ingress.domain") if labels.get(k)), None
    )
    paths = paths or ["/"]
    if configured_host:
        for path in paths:
            rules.append({"host": configured_host, "path": path, "port": first_port})
    elif host_sets:
        for hosts in host_sets:
            for h in hosts:
                for path in paths:
                    rules.append({"host": h, "path": path, "port": first_port})
    elif base_domain:
        web_ports = [p for p in container_ports if p in WEB_PORTS]
        for port_num in web_ports:
            for path in paths:
                rules.append({"host": base_domain, "path": path, "port": port_num})
    else:
        for port_num in container_ports:
            if port_num in WEB_PORTS:
                for path in paths:
                    rules.append({"host": "example.local", "path": path, "port": port_num})

    if not rules:
        return None

    tls_hosts = list(dict.fromkeys(r["host"] for r in rules))
    ingress = {"rules": rules}
    if tls:
        ingress.setdefault("tls", [{
            "hosts": tls_hosts,
            "secretName": f"{tls_hosts[0].replace('.', '-')}-tls"
        }])

    if ingress:
        ingress.setdefault("className", ingress_class)

    return ingress

